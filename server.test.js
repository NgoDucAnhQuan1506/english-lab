const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'english-lab-test-'));
delete process.env.DATABASE_URL;
delete process.env.ADMIN_EMAIL;
delete process.env.COURSE_EDITION;
process.env.NODE_ENV = 'development';
// Simulate an installation created before roles were introduced.
const { DatabaseSync: LegacyDatabase } = require('node:sqlite');
const legacy = new LegacyDatabase(path.join(process.env.DATA_DIR, 'english-lab.sqlite'));
legacy.exec('CREATE TABLE users (id TEXT PRIMARY KEY, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL, password TEXT NOT NULL, salt TEXT NOT NULL, progress TEXT NOT NULL)');
const legacyProgress = { currentIndex: 4, learned: [1, 2], favorites: [2], attempts: 1, correct: 1, days: ['2026-01-01'] };
legacy.prepare('INSERT INTO users VALUES (?, ?, ?, ?, ?, ?)').run('legacy', 'Legacy', 'legacy@example.com', '00'.repeat(64), 'salt', JSON.stringify(legacyProgress));
legacy.close();
const { server, db, ready } = require('./server');

test('account sessions, isolated persistent progress and validation', async t => {
  await ready;
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => {
    await new Promise(resolve => server.close(resolve));
    db.close();
    fs.rmSync(process.env.DATA_DIR, { recursive: true, force: true });
  });
  const base = `http://127.0.0.1:${server.address().port}`;
  const migrated = db.prepare("SELECT * FROM users WHERE id = 'legacy'").get();
  assert.equal(migrated.role, 'student');
  assert.equal(migrated.disabled, 0);
  assert.deepEqual(JSON.parse(migrated.progress), legacyProgress);
  async function call(route, data, cookie, extra = {}) {
    const response = await fetch(base + '/api/' + route, { method: data === undefined ? 'GET' : 'POST', headers: { ...(data === undefined ? {} : { 'Content-Type': 'application/json' }), ...(cookie ? { Cookie: cookie } : {}), ...extra }, body: data === undefined ? undefined : JSON.stringify(data) });
    return { status: response.status, cookie: response.headers.get('set-cookie')?.split(';')[0], headers: response.headers, body: await response.json() };
  }
  assert.equal((await call('me')).status, 401);
  assert.equal((await call('progress', { action: 'learn', index: 0 })).status, 401);
  assert.equal((await call('register', { name: 'An', email: 'bad', password: 'short' })).status, 400);
  const credentials = { name: 'An Nguyễn', email: 'An@Example.com', password: 'password123' };
  const registration = await call('register', credentials);
  assert.equal(registration.status, 200);
  assert.match(registration.headers.get('set-cookie'), /HttpOnly; SameSite=Lax/);
  assert.equal(registration.body.user.email, 'an@example.com');
  assert.equal(registration.body.user.password, undefined);
  const stored = db.prepare('SELECT * FROM users WHERE email = ?').get('an@example.com');
  assert.notEqual(stored.password, credentials.password);
  assert.equal(stored.password.length, 128);
  assert.equal((await call('register', credentials)).status, 409);
  assert.equal((await call('login', { ...credentials, password: 'wrongpassword' })).status, 401);
  const cookie = registration.cookie;
  assert.equal((await call('progress', { action: 'learn', index: 26 }, cookie)).status, 400);
  assert.equal((await call('progress', { action: 'learn', index: 0 }, cookie, { Origin: 'https://untrusted.example' })).status, 403);
  await call('progress', { action: 'learn', index: 2 }, cookie);
  assert.deepEqual((await call('me', undefined, cookie)).body.user.progress.learned, []);
  await call('progress', { action: 'learn', index: 2 }, cookie);
  await call('progress', { action: 'view', index: 7 }, cookie);
  await call('progress', { action: 'favorite', index: 4 }, cookie);
  await call('progress', { action: 'answer', index: 3, answer: 0 }, cookie);
  await call('progress', { action: 'answer', index: 3, answer: 3 }, cookie);
  await call('progress', { action: 'answer', index: 3, answer: 3 }, cookie);
  const progress = (await call('me', undefined, cookie)).body.user.progress;
  assert.deepEqual(progress.learned, [3]);
  assert.deepEqual(progress.favorites, [4]);
  assert.equal(progress.currentIndex, 7);
  assert.equal(progress.attempts, 3);
  assert.equal(progress.correct, 2);
  assert.equal(progress.days.length, 1);
  const second = await call('register', { name: 'Bình', email: 'binh@example.com', password: 'password456' });
  assert.deepEqual(second.body.user.progress.learned, []);
  await call('progress', { action: 'learn', index: 25, userId: stored.id }, second.cookie);
  assert.deepEqual((await call('me', undefined, cookie)).body.user.progress.learned, [3]);
  assert.equal((await call('logout', {}, cookie)).status, 200);
  assert.equal((await call('me', undefined, cookie)).status, 401);
  const login = await call('login', credentials);
  assert.equal(login.status, 200);
  assert.deepEqual(login.body.user.progress, progress);
  await Promise.all([8, 9, 10].map(index => call('progress', { action: 'learn', index }, login.cookie)));
  const updated = (await call('me', undefined, login.cookie)).body.user.progress;
  assert.deepEqual(updated.learned, [3]);
  assert.deepEqual(updated.viewed, [2, 7, 8, 9, 10]);
  const { DatabaseSync } = require('node:sqlite');
  const disk = new DatabaseSync(path.join(process.env.DATA_DIR, 'english-lab.sqlite'));
  assert.deepEqual(JSON.parse(disk.prepare('SELECT progress FROM users WHERE id = ?').get(stored.id).progress), updated);
  disk.close();
  // Admin APIs reject guests and ordinary learners, including crafted role fields.
  assert.equal((await call('admin/users')).status, 401);
  assert.equal((await call('admin/users', undefined, login.cookie)).status, 403);
  const adminCredentials = { name: 'Quản trị', email: 'admin@example.com', password: 'adminPassword123', role: 'admin', disabled: false };
  const pendingAdmin = await call('register', adminCredentials);
  assert.equal(pendingAdmin.body.user.role, 'student');
  assert.equal((await call('admin/users', undefined, pendingAdmin.cookie)).status, 403);
  const promoted = execFileSync(process.execPath, [path.join(__dirname, 'manage-admin.js'), adminCredentials.email], { encoding: 'utf8', env: process.env });
  assert.match(promoted, /Đã cấp quyền admin/);
  assert.equal((await call('me', undefined, pendingAdmin.cookie)).status, 401);
  const admin = await call('login', adminCredentials);
  assert.equal(admin.body.user.role, 'admin');
  const list = await call('admin/users', undefined, admin.cookie);
  assert.equal(list.status, 200);
  assert.equal(list.body.stats.total, 4);
  assert.equal(list.body.stats.admins, 1);
  assert.equal(list.body.users.some(user => 'password' in user || 'salt' in user), false);
  const filtered = await call('admin/users?q=binh%40example.com', undefined, admin.cookie);
  assert.equal(filtered.body.total, 1);
  assert.equal(filtered.body.users[0].email, 'binh@example.com');
  assert.equal((await call('admin/users?q=%27%20OR%201%3D1--', undefined, admin.cookie)).body.total, 0);
  assert.equal((await call('admin/users?page=-1', undefined, admin.cookie)).status, 400);
  assert.equal((await call('admin/users?status=invalid', undefined, admin.cookie)).status, 400);
  const detail = await call(`admin/users/${stored.id}`, undefined, admin.cookie);
  assert.deepEqual(detail.body.user.progress, updated);
  assert.equal((await call(`admin/users/${stored.id}`, undefined, second.cookie)).status, 403);
  const statusRoute = `admin/users/${stored.id}/status`;
  assert.equal((await call(statusRoute, { disabled: true }, second.cookie)).status, 403);
  assert.equal((await call(statusRoute, { disabled: 'true' }, admin.cookie)).status, 400);
  assert.equal((await call(statusRoute, { disabled: true }, admin.cookie, { Origin: 'https://untrusted.example' })).status, 403);
  assert.equal((await call(`admin/users/${admin.body.user.id}/status`, { disabled: true }, admin.cookie)).status, 403);
  const locked = await call(statusRoute, { disabled: true }, admin.cookie);
  assert.equal(locked.status, 200);
  assert.equal(locked.body.user.disabled, true);
  assert.equal((await call('me', undefined, login.cookie)).status, 401);
  assert.equal((await call('progress', { action: 'learn', index: 11 }, login.cookie)).status, 401);
  assert.equal((await call('login', credentials)).status, 403);
  assert.equal((await call('admin/users?status=disabled', undefined, admin.cookie)).body.total, 1);
  assert.equal((await call(statusRoute, { disabled: false }, admin.cookie)).status, 200);
  assert.equal((await call('me', undefined, login.cookie)).status, 401); // old sessions stay revoked
  const unlocked = await call('login', credentials);
  assert.equal(unlocked.status, 200);
  assert.deepEqual(unlocked.body.user.progress, updated);
  const { randomUUID } = require('node:crypto');
  const curriculum = require('./public/curriculum');
  const makeEvent = (type, values) => ({ id: randomUUID(), at: Date.now(), type, ...values });
  const run = randomUUID();
  const correctEvent = makeEvent('answer', { question: 'd1-p1', run, answer: curriculum.lessons[0].practice[0].answers[0] });
  const wrongEvent = makeEvent('answer', { question: 'd1-p2', run, answer: 'wrong', correct: true, day: 30 });
  assert.equal((await call('study', { events: [correctEvent] })).status, 401);
  const study = await call('study', { events: [correctEvent, wrongEvent], userId: second.body.user.id }, unlocked.cookie);
  assert.equal(study.status, 200);
  assert.equal(study.body.events.find(e => e.id === wrongEvent.id).correct, false);
  assert.equal(study.body.events.find(e => e.id === wrongEvent.id).day, 1);
  assert.deepEqual((await call('study', undefined, second.cookie)).body.events, []);
  const repeated = await call('study', { events: [correctEvent, wrongEvent] }, unlocked.cookie);
  assert.equal(repeated.body.events.length, 2);
  await Promise.all([makeEvent('favorite', { item: 'd1-v1', value: true }), makeEvent('view', { day: 2, step: 'vocab' })].map(event => call('study', { events: [event] }, unlocked.cookie)));
  assert.equal((await call('study', undefined, unlocked.cookie)).body.events.length, 4);
  assert.equal((await call('study', { events: [makeEvent('answer', { question: '__proto__', run, answer: 'yes' })] }, unlocked.cookie)).status, 400);
  const lessonRoute = 'admin/lessons/1';
  assert.equal((await call(lessonRoute, undefined, unlocked.cookie)).status, 403);
  const content = await call(lessonRoute, undefined, admin.cookie);
  assert.equal(content.status, 200);
  const draft = structuredClone(content.body.lesson); draft.title = 'Bài nháp đã kiểm tra';
  assert.equal((await call(lessonRoute, { action: 'draft', lesson: draft, version: content.body.version }, admin.cookie)).status, 200);
  assert.notEqual((await call('course')).body.lessons[0].title, draft.title);
  assert.equal((await call(lessonRoute, { action: 'publish', lesson: draft, version: content.body.version }, admin.cookie)).status, 409);
  const invalid = structuredClone(draft); invalid.practice[0].answers = ['not-an-option'];
  assert.equal((await call(lessonRoute, { action: 'publish', lesson: invalid, version: 1 }, admin.cookie)).status, 400);
  assert.equal((await call(lessonRoute, { action: 'publish', lesson: draft, version: 1 }, admin.cookie)).status, 200);
  assert.equal((await call('course')).body.lessons[0].title, draft.title);
  // Email alone never grants admin: a server-configured secret is also required.
  process.env.ADMIN_EMAIL = second.body.user.email;
  process.env.ADMIN_SETUP_KEY = randomUUID() + randomUUID();
  const envAdmin = await call('login', { email: second.body.user.email, password: 'password456' });
  assert.equal(envAdmin.body.user.role, 'student');
  assert.equal((await call('bootstrap-admin', { key: 'wrong' }, envAdmin.cookie)).status, 403);
  assert.equal((await call('bootstrap-admin', { key: process.env.ADMIN_SETUP_KEY }, unlocked.cookie)).status, 403);
  const bootstrap = await call('bootstrap-admin', { key: process.env.ADMIN_SETUP_KEY }, envAdmin.cookie);
  assert.equal(bootstrap.body.user.role, 'admin');
  assert.equal((await call('me', undefined, envAdmin.cookie)).status, 401);
  delete process.env.ADMIN_EMAIL;
  delete process.env.ADMIN_SETUP_KEY;
  const backup = path.join(process.env.DATA_DIR, 'consistent-backup.sqlite');
  execFileSync(process.execPath, [path.join(__dirname, 'backup-sqlite.js'), path.join(process.env.DATA_DIR, 'english-lab.sqlite'), backup], { encoding: 'utf8' });
  const snapshot = new LegacyDatabase(backup, { readOnly: true });
  assert.equal(snapshot.prepare('SELECT count(*) AS total FROM users').get().total, 4);
  assert.equal(JSON.parse(snapshot.prepare('SELECT study FROM users WHERE id = ?').get(stored.id).study).events.length, 4);
  snapshot.close();
  const F=require('./public/foundation'),Engine=require('./public/study-engine');
  assert.equal((await call('course?version=foundation-v2')).body.lessons.length,42);
  assert.equal((await call('course?version=legacy-v1')).body.lessons.length,30);
  assert.equal((await call('course?version=missing')).status,404);
  assert.equal((await call('settings')).body.courseEdition,'foundation-v2');
  process.env.COURSE_EDITION='legacy-v1';assert.equal((await call('settings')).body.courseEdition,'legacy-v1');delete process.env.COURSE_EDITION;
  const fRun=randomUUID(),fQuestion=F.lessons[0].practice[0];
  const fWrong=makeEvent('answer',{course:F.version,question:fQuestion.id,run:fRun,answer:'wrong',correct:true});
  const fCorrect=makeEvent('answer',{course:F.version,question:F.lessons[0].practice[1].id,run:fRun,answer:F.lessons[0].practice[1].answers[0],assisted:true});
  const fSaved=await call('study',{events:[fWrong,fCorrect]},bootstrap.cookie);assert.equal(fSaved.status,200);
  assert.equal(fSaved.body.events.find(e=>e.id===fWrong.id).correct,false,'server rejects forged correctness');
  assert.equal(fSaved.body.events.find(e=>e.id===fCorrect.id).assisted,true);
  const fRepeated=await call('study',{events:[{...fWrong,answer:fQuestion.answers[0]}]},bootstrap.cookie);
  assert.equal(fRepeated.body.events.find(e=>e.id===fWrong.id).correct,false,'server history wins on reused event ID');
  assert.equal((await call('study',{events:[makeEvent('view',{course:F.version,day:43,step:'intro'})]},bootstrap.cookie)).status,400);
  assert.equal((await call('study',{events:[makeEvent('answer',{course:'legacy-v1',question:fQuestion.id,run:fRun,answer:fQuestion.answers[0]})]},bootstrap.cookie)).status,400);
  assert.equal(Engine.state(fRepeated.body.events,F.lessons).assisted,1);
  const changedQuestion=structuredClone(draft);changedQuestion.practice[0].prompt='A different meaning';
  assert.equal((await call(lessonRoute,{action:'publish',lesson:changedQuestion,version:2},admin.cookie)).status,400,'legacy question semantics cannot be reused');
  db.prepare('UPDATE sessions SET expires = 0 WHERE user_id = ?').run(stored.id);
  assert.equal((await call('me', undefined, login.cookie)).status, 401);
  assert.equal((await fetch(base + '/data/english-lab.sqlite')).status, 404);
  assert.equal((await fetch(base + '/')).status, 200);
});
